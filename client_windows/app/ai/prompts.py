"""AI 提示词模板（M3 / M4.5）。

要求：统一 JSON 输出契约（对齐 docs/设计总纲.md 5.4），字段缺失时留空不瞎猜。

M4.5 起增加「层级判定」：
- level=goal（目标/项目）必须**同时**满足「截止时间距今 ≥ 30 天」与
  「需要持续投入、可分多阶段推进」两个条件，并向下拆解 2~5 个任务；
- level=task（任务）按需拆解子任务，宁缺勿碎；
- 时间远但一次性完成的事项（开会、体检、报到）仍判 task。
"""

from __future__ import annotations

from datetime import datetime

SYSTEM_PROMPT = (
    "你是研究生个人任务助理，负责把自然语言转成结构化任务数据。\n"
    "你必须且只能输出一个 JSON 对象，不要输出任何解释文字或 Markdown 代码块。\n"
    "信息不足的字段填 null，不要编造。"
)

# 解析任务的 JSON 输出契约
_PARSE_CONTRACT = """输出 JSON 字段定义：
{
  "level": "goal|task|subtask"，层级判定见下方「层级判定规则」,
  "level_confidence": 0.0到1.0之间的小数，仅表示你对层级判定的把握程度,
  "title": "一句话任务名/目标名（必填）",
  "priority": "P0|P1|P2|P3，P0=当天/紧急，P1=本周内，P2=本月内，P3=更远；不确定填 null",
  "task_type": "课程|科研|作业|考试|组会|生活|其他",
  "due_at": "截止/结束时间，ISO 8601 格式如 2026-10-10T23:59:00+08:00；没提到填 null，绝不瞎猜",
  "estimate_min": "完成任务本身需要投入的分钟数，不确定填 null；不是事件占用时长（如考试 145 分钟、会议 60 分钟之类不要填在这里）",
  "energy": "高|中|低，按任务难度判断；不确定填 null",
  "tags": ["标签1", "标签2"]，可空数组,
  "subtask_needed": true或false，先判断该任务是否有必要拆解子任务：一次动作即可完成（如取快递、回邮件、交表）则为false，多步骤任务为true（level=goal 时忽略本字段）,
  "subtasks": ["步骤1", "步骤2"]，执行步骤，按需拆解，宁缺勿碎：subtask_needed为false时必须为空数组；为true时给 2-6 个按顺序推进的步骤（level=goal 时留空数组）,
  "tasks": [{"title": "任务名", "due_at": "截止时间或null", "priority": "P0|P1|P2|P3", "estimate_min": 90, "subtask_needed": false, "subtasks": [], "depends_on": []}],
  "key_results": ["关键结果1", "关键结果2"],
  "description": "补充描述；没有则填空串",
  "advice": "怎么做才能做好的一段策略建议，80 字以内；只说明方法、重点与取舍，不要罗列具体动作",
  "checklist": ["完成前要确认的事项1", "…"]，可空数组,
  "confidence": 0.0到1.0之间的小数，表示你对以上解析的把握程度
}

层级判定规则（必须遵守）：
1. 判 goal 必须同时满足两条：① 截止时间距当前时间 ≥ 30 天；② 这件事需要持续投入、能拆成多个阶段推进（备考、写论文、学一门课、做一个项目）。
   缺任意一条就判 task：时间虽远但一次就能办完的事（参加一场会议、体检、报到、领材料、听讲座）一律判 task，
   即使它需要提前做一些准备，也只是 task 的 subtasks，不要升格成 goal。
2. level=goal 时：tasks 必填，给 2~5 个能真正推进该目标的 L2 任务（按执行顺序排列，每项是一整天到数周可完成的任务）；
   tasks 各项的 depends_on 写「必须先完成的前置任务在数组中的序号」（从 0 开始，可多个）：
   只有当前置任务完成后本任务才能开始时才填（例如先报名才能打印准考证、先摸底才能针对性复习）；
   无前置约束的任务留空数组。数组顺序必须与实际推进顺序一致，禁止把后做的任务排在前面；
   key_results 给 2~4 条可验收的关键结果；advice 必须给出达成该目标的策略（例如先摸底、按薄弱项分配精力、阶段验收），
   不能只是「认真准备」这类空话；
   输入中出现的中间时间节点（报名截止、打印准考证、模拟考等）用一条带 due_at 的 tasks 记录承接，不要另设概念；
   subtasks 留空数组。
3. level=task 时：tasks 必须为空数组；输入中出现的中间时间节点（如打印准考证）作为一条 subtasks 写进执行步骤，
   再按 subtask_needed 判断是否拆分子任务，宁可少拆也绝不为凑数硬拆成细碎动作。
4. level=subtask 时：tasks、subtasks 都必须为空数组。

考试/论文/项目等「有明确日期且距今 ≥30 天」的节点：应判 goal，title 用「准备 XXX」这类体现持续投入的说法，
due_at 保留该节点日期，报名截止/打印准考证/模拟考等中间节点写成带 due_at 的 tasks，
但一次性出行类事件（开会、体检、报到、讲座、面试）例外，仍判 task。

subtasks 与 checklist 的边界（必须遵守）：
- subtasks 是「需要投入时间去做的工作步骤」，带推进顺序；
- checklist 是「一次性的核对项/携带物」（带身份证、打印准考证、确认考场），不要写进 subtasks；
- 同一件事不要同时出现在两处。

置信度自评标准：描述清晰且关键信息齐全 > 0.7；部分信息需推断 0.4~0.7；描述模糊或几乎无法理解 < 0.4（此时 title 尽量保留原话）。"""

# 模型把「目标」误判成 task 时的追问后缀（由 parser 触发，最多追加一次）
GOAL_RETRY_SUFFIX = (
    "\n\n请再检查一次层级：这个事项的截止时间距今超过 30 天，且需要持续投入、"
    '可以分阶段推进，应按 level="goal" 输出，并给出 2~5 个 L2 任务、关键结果与达成策略。'
    "如果你确认它只是一次性能办完的事（会议、体检、报到等），请保持 task 判定。"
)



def build_parse_user_prompt(text: str, now: datetime) -> str:
    """构造「一句话 → 结构化任务」的用户消息。

    附带当前时间，让「明天下午」「下周一」这类相对时间可以正确换算。
    """
    weekday = "一二三四五六日"[now.weekday()]
    return (
        f"当前时间：{now.strftime('%Y-%m-%d %H:%M')}（星期{weekday}，时区 UTC+8）\n"
        f"请把下面这句话解析为结构化任务。\n\n用户输入：{text}\n\n{_PARSE_CONTRACT}"
    )


def build_breakdown_user_prompt(title: str, description: str, now: datetime) -> str:
    """构造「已有任务 → 拆解建议」的用户消息。"""
    desc = description.strip() or "（无补充描述）"
    return (
        f"当前时间：{now.strftime('%Y-%m-%d %H:%M')}（时区 UTC+8）\n"
        "请为下面这个已有任务生成拆解建议（只是建议，我不会自动改状态）。\n\n"
        f"任务名：{title}\n"
        f"补充描述：{desc}\n\n"
        "输出 JSON 字段定义：\n"
        "{\n"
        '  "subtasks": ["需要投入时间去做的步骤1", "步骤2", …]，按需拆解，宁缺勿碎：'
        "任务本身一次就能完成或步骤高度单一时输出空数组，绝不为凑数硬拆；"
        "确需拆解时给 2-8 步，按执行顺序，每步都是可独立完成验证的工作步骤,\n"
        '  "checklist": ["一次性的核对项/携带物", …]，可空数组,\n'
        '  "advice": "怎么才能把这件事做好的策略建议（80 字以内）：说明重点、方法与取舍，'
        '例如先摸底再按薄弱项分配精力；不要只写「认真准备」，也不要罗列具体动作",\n'
        '  "confidence": 0.0到1.0之间的小数\n'
        "}\n"
        "subtasks 与 checklist 的边界：subtasks 是要花时间做的工作步骤；"
        "checklist 是打印、携带、核对类的一次性事项，两者不要重复。\n"
    )
